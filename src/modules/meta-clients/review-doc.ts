import { COMPANY } from "../../company.js";
import { META_PERMISSIONS } from "./permissions.js";

/** The text of docs/META-APP-REVIEW.md. Generated: edit permissions.ts, not the file. */
export function metaReviewDoc(): string {
  const per = META_PERMISSIONS.map((p) => `### \`${p.key}\`

**Used for:** ${p.kinds.join(", ")}. **Shown to the client as:** "${p.plain}"

**How to answer "How will your app use this permission?"** (paste into the App Review form)

> ${p.justification}

**Screencast script** (one recording per permission; English captions on; show the browser address bar throughout)

${p.screencast.map((s, i) => `${i + 1}. ${s}`).join("\n")}
`).join("\n");

  return `<!-- Generated by scripts/build-meta-docs.ts from src/modules/meta-clients/permissions.ts. Do not edit by hand: run \`npm run docs:meta\`. -->
# Meta App Review pack for ${COMPANY.name}

MAIZ applies to Meta as a **Tech Provider** (a service provider acting for client businesses). This is everything Meta asks for, in the order the App Review form asks for it. Status of each item is tracked on the owner page \`/owner-meta.html\`.

## 1. App settings to enter in the Meta dashboard

All addresses are shown ready to copy on \`/owner-meta.html\` (they depend on APP_URL). In short:

| Field | Value |
|---|---|
| Privacy Policy URL | \`<APP_URL>/privacy.html\` (has a Meta section, section id \`meta\`) |
| Terms of Service URL | \`<APP_URL>/terms.html\` (has a "Connecting Facebook, Instagram and WhatsApp" section) |
| User data deletion | Data deletion request URL \`<APP_URL>/api/meta/data-deletion\`, or instructions URL \`<APP_URL>/data-deletion.html\` |
| Deauthorize callback URL | \`<APP_URL>/api/meta/deauthorize\` |
| Valid OAuth redirect URI | \`<APP_URL>/api/meta/callback\` |
| WhatsApp webhook callback URL | \`<APP_URL>/api/meta/webhook\` (verify token = \`META_WEBHOOK_VERIFY_TOKEN\`; subscribe to \`messages\`) |
| App icon, category | 1024x1024 icon (use the MAIZ hat logo), category "Business and pages" |

## 2. Before you submit

- [ ] Business verification complete for ${COMPANY.name} (company number ${COMPANY.number}) in Meta Business Manager. Required for advanced access and Tech Provider status.
- [ ] Tech Provider onboarding done (Meta's Tech Provider requirements, including the required access verification for WhatsApp).
- [ ] \`META_MODE=live\`, \`META_APP_ID\`, \`META_APP_SECRET\`, \`META_WEBHOOK_VERIFY_TOKEN\`, \`META_LOGIN_CONFIG_ID\`, \`META_WHATSAPP_CONFIG_ID\` set (see docs/META-SERVICE-PROVIDER.md). The "Ready to go live?" list on \`/owner-meta.html\` must be all green.
- [ ] Facebook Login for Business configuration created with exactly the permissions below, and the WhatsApp Embedded Signup configuration created.
- [ ] Test users added under App roles (Roles > Test users / Testers). While the app is in Development mode these people can use every flow with real Meta, no review needed.
- [ ] Reviewer instructions filled in (section 3), with a working test login. Create a dedicated test business on MAIZ whose email is a throwaway, with a test Facebook Page, Instagram professional account and WhatsApp test number.
- [ ] Privacy, terms, deletion pages load without sign-in (the readiness list fetches them).
- [ ] Data deletion callback tested: Facebook "Test" button on the Data deletion callback returns a code and the status URL loads.

## 3. Notes for the reviewer (paste into "Notes")

> MAIZ Agents is a store of AI employees for small businesses. A business owner connects their own Facebook Page, Instagram professional account and WhatsApp Business number. The AI marketing employee drafts posts; every post waits for the owner's explicit approval (in the dashboard, or by replying Yes on WhatsApp) before anything is published. MAIZ never posts to an account the owner did not select, never messages anyone except the owner's own confirmed approver number, and deletes all Meta data on request or when the owner removes the app. To test: sign in at <APP_URL>/signin.html with the test account provided, open "Social accounts" in the left menu, and follow the screencast for each permission.

## 4. Per-permission justification and screencast scripts

${per}
## 5. Things reviewers commonly reject (check before submitting)

- A screencast that shows a permission being granted but not **used**. Every script above ends with the visible result on Facebook, Instagram or WhatsApp itself.
- A requested permission with no visible feature. If a feature is cut, remove its permission from \`permissions.ts\` and the Facebook Login for Business configuration.
- Privacy policy that does not name the data. Ours lists what is received, why, and how to delete it.
- Test credentials that no longer work. Re-check them the day you submit.
`;
}
